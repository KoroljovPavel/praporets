package io.praporets.core.evaluation;

/**
 * Чому обчислення дало саме цей варіант — відповідь на перше питання дебагу
 * «чому флаг поводиться дивно».
 *
 * <p>Тут лише причини, які породжує чисте ядро. Транспортний {@code ERROR}
 * з proto-контракту сюди свідомо не входить: ядро тотальне і помилок не
 * породжує — {@code ERROR} мапиться на рівні сервісів.
 */
public enum Reason {
    /**
     * {@code enabled == false} — віддано {@code offVariant}.
     */
    FLAG_DISABLED,
    /** Збіглося правило з фіксованим варіантом; {@code ruleId} вказує, яке саме. */
    RULE_MATCH,
    /** Відсотковий розподіл — правила ({@code ruleId} заданий) або конфігурації флага. */
    ROLLOUT,
    /** Жодне правило не збіглось, rollout відсутній — {@code defaultVariant}. */
    DEFAULT,
    /** Флага немає в конфігурації середовища; значення підставляє клієнт. */
    FLAG_NOT_FOUND
}
